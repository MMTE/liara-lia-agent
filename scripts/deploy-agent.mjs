#!/usr/bin/env node
/**
 * Deploy the agent app (this repo) to Liara via the platform API —
 * the same flow as `liara deploy` (create-archive → upload source →
 * create release), driven directly with DEMO_LIARA_TOKEN + LIARA_TEAM_ID.
 *
 *   node scripts/deploy-agent.mjs [--release-only]
 *
 * Reads from .env (or the environment):
 *   DEMO_LIARA_TOKEN   — Liara API token (team member)
 *   LIARA_TEAM_ID      — team scope for every API call
 *   LIARA_API_BASE     — default https://api.iran.liara.ir
 *   LIARA_APP_NAME     — default liara-lia-agent
 *   AGENT_PUBLIC_URL   — default https://<name>.liara.run
 *   DOCS_PUBLIC_URL    — default https://liara-lia-docs.liara.run
 *   CHAT_PROVIDER, AI_GATEWAY_API_KEY, OPENROUTER_API_KEY, CHAT_MODEL —
 *   passed as runtime envs on the release (never baked into the tarball).
 *
 * NEXT_PUBLIC_DOCS_SITE_ORIGIN is written into a generated .env.production
 * inside the tarball (gitignored locally) so the public origin is inlined
 * during Liara's build regardless of build-env injection.
 */
import { execSync } from "node:child_process";
import { mkdtempSync, cpSync, writeFileSync, rmSync, readFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const API = process.env.LIARA_API_BASE || "https://api.iran.liara.ir";
const APP = process.env.LIARA_APP_NAME || "liara-lia-agent";
const AGENT_URL = (process.env.AGENT_PUBLIC_URL || `https://${APP}.liara.run`).replace(/\/+$/, "");
const DOCS_URL = (process.env.DOCS_PUBLIC_URL || `https://liara-lia-docs.liara.run`).replace(/\/+$/, "");

function envFromDotenv() {
  try {
    const raw = readFileSync(new URL("../.env", import.meta.url), "utf8");
    const out = {};
    for (const line of raw.split("\n")) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m) out[m[1]] = m[2];
    }
    return out;
  } catch {
    return {};
  }
}

const dotenv = envFromDotenv();
const TOKEN = process.env.DEMO_LIARA_TOKEN || dotenv.DEMO_LIARA_TOKEN;
const TEAM = process.env.LIARA_TEAM_ID || dotenv.LIARA_TEAM_ID;
if (!TOKEN || !TEAM) throw new Error("DEMO_LIARA_TOKEN and LIARA_TEAM_ID are required (env or .env)");

const api = (pathname, init) =>
  fetch(`${API}/${pathname.replace(/^\//, "")}${pathname.includes("?") ? "&" : "?"}teamID=${TEAM}`, {
    ...init,
    headers: {
      // The API gates request shapes on the client UA (older clients get a
      // 400 upgrade-notice) — send a current CLI signature.
      "User-Agent": "liara-cli/9.5.1 (darwin arm64; x64)",
      authorization: `Bearer ${TOKEN}`,
      ...(init?.headers || {}),
    },
  });

const EXCLUDE = new Set([
  ".git", "node_modules", ".next", ".eve", ".env", "docs-site", "prototype",
  "lia-picture-assets", ".research", ".cache", ".worktrees", ".superpowers",
  "out", "dist", "coverage", ".DS_Store", "tsconfig.tsbuildinfo", ".gateway-probe.log",
]);

/**
 * withEve bakes /eve/* → 127.0.0.1:<port> into the routes manifest and
 * scripts/start.mjs supervises the sidecar from this prebuilt output
 * (Next 16 `next start` never re-evaluates rewrites, so the lazy spawn
 * withEve promises does not fire — see scripts/start.mjs).
 */
function buildEveOutput() {
  execSync("npx eve build", { stdio: "inherit", cwd: path.resolve(new URL("..", import.meta.url).pathname) });
  const entry = path.resolve(".output", "server", "index.mjs");
  if (!existsSync(entry)) throw new Error("eve build did not produce .output/server/index.mjs");
}

function buildTarball() {
  buildEveOutput();
  const stage = mkdtempSync(path.join(tmpdir(), "lia-agent-"));
  const root = new URL("..", import.meta.url).pathname;
  const entries = execSync(`ls -A ${root}`, { encoding: "utf8" }).split("\n").filter(Boolean);
  for (const name of entries) {
    if (EXCLUDE.has(name) || /\.log$/.test(name)) continue;
    cpSync(path.join(root, name), path.join(stage, name), { recursive: true, verbatimSymlinks: true });
  }
  // Public build-time env — inlined by `next build` on Liara (ADR-0008 cross-wire).
  writeFileSync(
    path.join(stage, ".env.production"),
    `# generated by scripts/deploy-agent.mjs — build-time public config\nNEXT_PUBLIC_DOCS_SITE_ORIGIN=${DOCS_URL}\n`
  );
  const tarPath = `${stage}.tar.gz`;
  execSync(`tar -czf ${tarPath} -C ${stage} .`, { stdio: "inherit" });
  rmSync(stage, { recursive: true, force: true });
  return tarPath;
}

async function uploadSource(tarPath) {
  const buf = readFileSync(tarPath);
  // Node 18 FormData + Blob: multipart without external deps.
  const form = new FormData();
  form.append("file", new Blob([buf], { type: "application/gzip" }), "source.tar.gz");
  const res = await api(`v2/projects/${APP}/sources`, { method: "POST", body: form });
  if (!res.ok) throw new Error(`sources upload failed: ${res.status} ${await res.text()}`);
  const { sourceID } = await res.json();
  console.log(`source uploaded: ${sourceID}`);
  return sourceID;
}

function runtimeEnvs() {
  const envs = {};
  for (const key of ["CHAT_PROVIDER", "CHAT_MODEL", "AVALAI_API_KEY", "AVALAI_BASE_URL", "AI_GATEWAY_API_KEY", "OPENROUTER_API_KEY", "LIARA_API_BASE", "DEMO_LIARA_TOKEN", "LIARA_TEAM_ID"]) {
    const v = process.env[key] || dotenv[key];
    if (v) envs[key] = v;
  }
  envs.LIARA_API_BASE = envs.LIARA_API_BASE || API;
  return envs;
}

async function main() {
  const tarPath = buildTarball();
  try {
    const sourceID = await uploadSource(tarPath);
    const body = {
      sourceID,
      port: 3000,
      // Liara's managed Next platform bypasses package.json's start command,
      // so it cannot run our Next + Eve supervisor. The Node platform honors
      // npm start while still running npm build for this Next application.
      type: "node",
      envs: runtimeEnvs(),
      build: {},
      message: "Lia agent — widget sidebar/history, team-scoped tools",
    };
    const res = await api(`v2/projects/${APP}/releases`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(body),
    });
    const text = await res.text();
    if (!res.ok) throw new Error(`release create failed: ${res.status} ${text}`);
    const { releaseID } = JSON.parse(text);
    console.log(`release created: ${releaseID}`);
    console.log(`agent url: ${AGENT_URL}`);

    // Poll the release until it leaves the queue + build states.
    const start = Date.now();
    for (;;) {
      await new Promise((r) => setTimeout(r, 5000));
      const r = await api(`v1/releases/${releaseID}`);
      if (!r.ok) throw new Error(`release poll failed: ${r.status} ${await r.text()}`);
      const { release } = await r.json();
      const state = release.state;
      process.stdout.write(`\r[${Math.round((Date.now() - start) / 1000)}s] ${state}${release.queue ? ` (queue: ${release.queue})` : "           "}\x1b[K`);
      if (state === "READY") {
        console.log(`\nRELEASE READY → ${AGENT_URL}`);
        return;
      }
      if (state === "FAILED" || state === "UNHEALTHY") {
        throw new Error(`release ${state}: ${release.failReason || "check logs via GET /v1/projects/" + APP + "/logs"}`);
      }
    }
  } finally {
    rmSync(tarPath, { force: true });
  }
}

main().catch((err) => {
  console.error(String(err));
  process.exit(1);
});
